    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
try {

    // Capture customer name
    String customerName = txtCustomerName.getText();

    // Capture selected product
    String productName = cmbProduct.getSelectedItem().toString();

    // Capture product price
    double price = Double.parseDouble(txtPrice.getText());

    // Calculate VAT (15%)
    double vat = price * 0.15;

    // Calculate commission (5%)
    double commission = price * 0.05;

    // Calculate total sale amount
    double total = price + vat + commission;

    // Display the results
    String message = "Customer Name: " + customerName
            + "\nProduct: " + productName
            + "\nVAT: R " + vat
            + "\nCOMMISSION: R " + commission
            + "\nTOTAL: R " + total;

    JOptionPane.showMessageDialog(this, message);

    // Save information to data.txt
    try {

        FileWriter writer = new FileWriter("data.txt", true);

        writer.write("DATA LOG\n");
        writer.write("************************\n");
        writer.write(message + "\n");
        writer.write("************************\n\n");

        writer.close();
        
        //displays an error message if the file fails to save the data
    } catch (IOException e) {

        JOptionPane.showMessageDialog(this,"Error saving data to file: " + e.getMessage());

    }
    //displays an error message if the user enters numbers incorrectly
} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(this, "Please enter a valid product price.");

}

    }//GEN-LAST:event_jButton1ActionPerformed

